def print_solar_summary(simulation_results):
    """Print the main results in a readable format."""

    print("\n" + "=" * 55)
    print("       FLUXXWAVE SOLAR ENERGY REPORT")
    print("=" * 55)

    # Display the parameters used by the model.
    print(
        f"Panel area:              "
        f"{simulation_results['panel_area_m2']:.2f} m²"
    )
    print(
        f"Panel efficiency:        "
        f"{simulation_results['panel_efficiency'] * 100:.1f}%"
    )
    print(
        f"Panel temperature:       "
        f"{simulation_results['temperature_c']:.1f} °C"
    )
    print(
        f"Shading fraction:        "
        f"{simulation_results['shading_fraction'] * 100:.1f}%"
    )
    print(
        f"System efficiency:       "
        f"{simulation_results['system_efficiency'] * 100:.1f}%"
    )

    print("-" * 55)

    # Display the simulated performance results.
    print(
        f"Peak power:              "
        f"{simulation_results['peak_power_w']:.2f} W"
    )
    print(
        f"Average sampled power:   "
        f"{simulation_results['average_power_w']:.2f} W"
    )
    print(
        f"Daily energy:            "
        f"{simulation_results['daily_energy_wh']:.2f} Wh"
    )
    print(
        f"Daily energy:            "
        f"{simulation_results['daily_energy_kwh']:.4f} kWh"
    )

    print("=" * 55)
    print("These are simulated estimates, not measured EV results.")
    print("=" * 55 + "\n")


