
"""
FLUXXWAVE — Solar Energy Generation Model
----------------------------------------
Purpose:
    Simulate the electrical energy generated by photovoltaic panels
    installed on the roof and bonnet of an electric vehicle.

Main features:
    1. Calculate solar panel output power.
    2. Estimate solar energy generated over time.
    3. Simulate changing sunlight throughout the day.
    4. Account for shading, temperature, and system losses.
    5. Estimate daily energy in Wh and kWh.
    6. Export simulation data to CSV.
    7. Plot irradiance, power, and accumulated energy.

Important:
    This is a simplified engineering simulation, not a real-time
    measurement system or a validated vehicle performance model.
"""
import csv
import math
import random
from datetime import datetime, timedelta
from pathlib import Path


# ============================================================
# SECTION 1: PROJECT CONFIGURATION
# ============================================================

# Default total panel area across the roof and bonnet, in m².
DEFAULT_PANEL_AREA_M2 = 2.0

# Example panel conversion efficiency: 22%.
DEFAULT_PANEL_EFFICIENCY = 0.22

# Maximum reference irradiance used in the example, in W/m².
DEFAULT_PEAK_IRRADIANCE = 900.0

# Fraction of power retained after solar-system conversion losses.
DEFAULT_SYSTEM_EFFICIENCY = 0.95

# Fraction of sunlight blocked by shading.
# 0.0 means no shading; 0.5 means 50% of incident light is blocked.
DEFAULT_SHADING_FRACTION = 0.0

# Approximate power temperature coefficient per degree Celsius.
# This example assumes power decreases by 0.4% per degree above 25°C.
DEFAULT_TEMP_COEFFICIENT = -0.004

# Reference temperature for the panel's rated efficiency.
REFERENCE_TEMPERATURE_C = 25.0

# Default simulation interval, in minutes.
DEFAULT_STEP_MINUTES = 10


# ============================================================
# SECTION 2: INPUT VALIDATION
# ============================================================

def validate_non_negative(value, name):
    """Reject negative numerical inputs."""
    if not isinstance(value, (int, float)):
        raise TypeError(f"{name} must be a number.")

    if not math.isfinite(value):
        raise ValueError(f"{name} must be finite.")

    if value < 0:
        raise ValueError(f"{name} cannot be negative.")

    return float(value)


def validate_fraction(value, name):
    """Validate a fraction between zero and one."""
    value = validate_non_negative(value, name)

    if value > 1:
        raise ValueError(f"{name} must be between 0 and 1.")

    return value


def validate_positive(value, name):
    """Reject zero and negative numerical inputs."""
    value = validate_non_negative(value, name)

    if value == 0:
        raise ValueError(f"{name} must be greater than zero.")

    return value


# ============================================================
# SECTION 3: BASIC SOLAR POWER CALCULATION
# ============================================================

def calculate_solar_power(
    irradiance_w_m2,
    panel_area_m2,
    panel_efficiency,
    shading_fraction=0.0,
    temperature_factor=1.0,
    system_efficiency=1.0,
):
    """
    Calculate estimated electrical output from a solar panel.

    Formula:
        P = G * A * eta * (1 - shading) * temperature_factor
            * system_efficiency

    Parameters:
        irradiance_w_m2:
            Solar power incident per square metre (W/m²).

        panel_area_m2:
            Effective illuminated panel area (m²).

        panel_efficiency:
            Fraction of incident solar energy converted to electricity.

        shading_fraction:
            Fraction of incoming sunlight blocked by shading.

        temperature_factor:
            Relative power factor due to panel temperature.

        system_efficiency:
            Fraction of power retained after electrical conversion losses.

    Returns:
        Estimated electrical power in watts (W).
    """

    # Check that the physical inputs are valid.
    irradiance = validate_non_negative(
        irradiance_w_m2, "irradiance_w_m2"
    )
    area = validate_non_negative(panel_area_m2, "panel_area_m2")
    efficiency = validate_fraction(
        panel_efficiency, "panel_efficiency"
    )
    shading = validate_fraction(
        shading_fraction, "shading_fraction"
    )
    temp_factor = validate_non_negative(
        temperature_factor, "temperature_factor"
    )
    system_factor = validate_fraction(
        system_efficiency, "system_efficiency"
    )

    # Calculate the solar power incident on the panel surface.
    incident_power = irradiance * area

    # Estimate how much incident power remains after shading.
    unshaded_power = incident_power * (1.0 - shading)

    # Apply photovoltaic conversion efficiency.
    electrical_power = unshaded_power * efficiency

    # Apply temperature and electrical system correction factors.
    adjusted_power = (
        electrical_power * temp_factor * system_factor
    )

    # Return the final estimated electrical output.
    return adjusted_power


# ============================================================
# SECTION 4: TEMPERATURE CORRECTION
# ============================================================

def calculate_temperature_factor(
    panel_temperature_c,
    reference_temperature_c=REFERENCE_TEMPERATURE_C,
    temperature_coefficient=DEFAULT_TEMP_COEFFICIENT,
):
    """
    Estimate the effect of panel temperature on electrical power.

    The linear approximation is:
        factor = 1 + coefficient * (panel_temp - reference_temp)

    The coefficient is normally negative for common PV modules.

    This simplified model does not represent every panel technology
    or all temperature-dependent electrical behaviour.
    """

    if not isinstance(panel_temperature_c, (int, float)):
        raise TypeError("Panel temperature must be a number.")

    if not math.isfinite(panel_temperature_c):
        raise ValueError("Panel temperature must be finite.")

    if not math.isfinite(reference_temperature_c):
        raise ValueError("Reference temperature must be finite.")

    if not math.isfinite(temperature_coefficient):
        raise ValueError("Temperature coefficient must be finite.")

    # Find the difference from the reference temperature.
    temperature_difference = (
        panel_temperature_c - reference_temperature_c
    )

    # Estimate the relative power correction.
    factor = (
        1.0 + temperature_coefficient * temperature_difference
    )

    # Prevent a physically meaningless negative output factor.
    return max(0.0, factor)


# ============================================================
# SECTION 5: SIMULATING SUNLIGHT THROUGHOUT THE DAY
# ============================================================

def simulate_irradiance(
    sunrise_hour=6.0,
    sunset_hour=18.0,
    peak_irradiance=DEFAULT_PEAK_IRRADIANCE,
    step_minutes=DEFAULT_STEP_MINUTES,
    cloud_variability=0.0,
    random_seed=42,
):
    """
    Generate a simplified daylight irradiance time series.

    The model uses a half-sine daylight curve:
        G(t) = G_peak * sin(pi * daylight_position)

    Irradiance is zero outside the simulated daylight period.

    Parameters:
        sunrise_hour:
            Sunrise time in decimal hours, e.g. 6.0 means 06:00.

        sunset_hour:
            Sunset time in decimal hours, e.g. 18.0 means 18:00.

        peak_irradiance:
            Peak reference irradiance in W/m².

        step_minutes:
            Time between consecutive simulation samples.

        cloud_variability:
            Maximum fractional reduction due to simulated clouds.
            For example, 0.3 allows reductions of up to 30%.

        random_seed:
            Fixed seed for reproducible simulated cloud conditions.

    Returns:
        A list of dictionaries containing time and irradiance.
    """

    # Validate the main numerical parameters.
    sunrise = validate_non_negative(sunrise_hour, "sunrise_hour")
    sunset = validate_non_negative(sunset_hour, "sunset_hour")
    peak = validate_non_negative(
        peak_irradiance, "peak_irradiance"
    )
    step = validate_positive(step_minutes, "step_minutes")
    clouds = validate_fraction(
        cloud_variability, "cloud_variability"
    )

    # A single-day simulation must fit within 24 hours.
    if sunrise >= 24 or sunset > 24:
        raise ValueError("Sunrise and sunset must fit within 24 hours.")

    if sunset <= sunrise:
        raise ValueError("Sunset must occur after sunrise.")

    # Use a local random generator so the result is reproducible.
    rng = random.Random(random_seed)

    # Convert the interval from minutes to hours.
    step_hours = step / 60.0

    # Calculate the length of the daylight period.
    daylight_duration = sunset - sunrise

    # Prepare the list that will hold all generated samples.
    irradiance_data = []

    # Generate samples from midnight through the end of the day.
    number_of_steps = math.ceil(24.0 / step_hours)

    for index in range(number_of_steps + 1):

        # Determine the current simulation time.
        hour = index * step_hours

        # Stop if the sample falls beyond the end of the day.
        if hour > 24.0:
            break

        # Default to zero irradiance outside daylight hours.
        irradiance = 0.0

        if sunrise <= hour <= sunset:

            # Locate the sample within the daylight period.
            daylight_position = (
                (hour - sunrise) / daylight_duration
            )

            # Calculate the idealised daylight curve.
            solar_angle = math.pi * daylight_position

            irradiance = peak * math.sin(solar_angle)

            # Keep the calculated value non-negative.
            irradiance = max(0.0, irradiance)

            # Apply a random cloud-related reduction if enabled.
            if clouds > 0:
                cloud_factor = rng.uniform(1.0 - clouds, 1.0)
                irradiance *= cloud_factor

        # Save the sample for later power calculations.
        irradiance_data.append({
            "time_hours": round(hour, 6),
            "irradiance_w_m2": round(irradiance, 4),
        })

    return irradiance_data


# ============================================================
# SECTION 6: CALCULATING ENERGY FROM POWER
# ============================================================

def calculate_solar_energy(power_w, time_hours):
    """
    Calculate electrical energy from power samples using
    the trapezoidal numerical integration method.

    Parameters:
        power_w:
            A list of power samples in watts.

        time_hours:
            Corresponding simulation times in decimal hours.

    Returns:
        Total estimated electrical energy in watt-hours (Wh).

    Example:
        Power = [100, 200, 100] W
        Time  = [0, 1, 2] hours

        Energy = 150 + 150 = 300 Wh
    """

    # Ensure both input arrays contain corresponding samples.
    if len(power_w) != len(time_hours):
        raise ValueError(
            "Power and time arrays must have equal lengths."
        )

    # At least two samples are needed for integration.
    if len(power_w) < 2:
        return 0.0

    # Validate all sample values.
    powers = [
        validate_non_negative(value, "power_w")
        for value in power_w
    ]

    times = [
        validate_non_negative(value, "time_hours")
        for value in time_hours
    ]

    # Calculate energy across each consecutive pair of samples.
    total_energy_wh = 0.0

    for index in range(len(powers) - 1):

        # Determine the time between the current samples.
        time_interval = times[index + 1] - times[index]

        if time_interval <= 0:
            raise ValueError(
                "Time samples must be strictly increasing."
            )

        # Estimate average power over this time interval.
        average_power = (
            powers[index] + powers[index + 1]
        ) / 2.0

        # Energy equals average power multiplied by elapsed hours.
        interval_energy = average_power * time_interval

        # Accumulate the energy produced during this interval.
        total_energy_wh += interval_energy

    return total_energy_wh


# ============================================================
# SECTION 7: COMPLETE SOLAR DAY SIMULATION
# ============================================================

def simulate_solar_day(
    panel_area_m2=DEFAULT_PANEL_AREA_M2,
    panel_efficiency=DEFAULT_PANEL_EFFICIENCY,
    peak_irradiance=DEFAULT_PEAK_IRRADIANCE,
    sunrise_hour=6.0,
    sunset_hour=18.0,
    step_minutes=DEFAULT_STEP_MINUTES,
    shading_fraction=DEFAULT_SHADING_FRACTION,
    panel_temperature_c=35.0,
    system_efficiency=DEFAULT_SYSTEM_EFFICIENCY,
    cloud_variability=0.0,
    random_seed=42,
):
    """
    Simulate an entire day's solar power generation.

    This function connects the irradiance model, temperature
    correction, power calculation, and energy integration.

    Returns:
        A dictionary containing time-series data and summary metrics.
    """

    # Generate a hypothetical sunlight profile for the day.
    irradiance_data = simulate_irradiance(
        sunrise_hour=sunrise_hour,
        sunset_hour=sunset_hour,
        peak_irradiance=peak_irradiance,
        step_minutes=step_minutes,
        cloud_variability=cloud_variability,
        random_seed=random_seed,
    )

    # Calculate the temperature correction for the selected conditions.
    temperature_factor = calculate_temperature_factor(
        panel_temperature_c
    )

    # Prepare arrays to store the simulation results.
    time_hours = []
    irradiance_values = []
    power_values = []
    results = []

    for sample in irradiance_data:

        # Extract the current time and sunlight intensity.
        hour = sample["time_hours"]
        irradiance = sample["irradiance_w_m2"]

        # Calculate the panel's estimated electrical power.
        power = calculate_solar_power(
            irradiance_w_m2=irradiance,
            panel_area_m2=panel_area_m2,
            panel_efficiency=panel_efficiency,
            shading_fraction=shading_fraction,
            temperature_factor=temperature_factor,
            system_efficiency=system_efficiency,
        )

        # Store the values for numerical integration and analysis.
        time_hours.append(hour)
        irradiance_values.append(irradiance)
        power_values.append(power)

        # Store a detailed record for this time step.
        results.append({
            "time_hours": hour,
            "irradiance_w_m2": round(irradiance, 4),
            "temperature_c": panel_temperature_c,
            "temperature_factor": round(temperature_factor, 5),
            "power_w": round(power, 4),
        })

    # Integrate power over time to estimate total daily energy.
    daily_energy_wh = calculate_solar_energy(
        power_values, time_hours
    )

    # Convert watt-hours to kilowatt-hours.
    daily_energy_kwh = daily_energy_wh / 1000.0

    # Find the maximum estimated power during the simulation.
    peak_power_w = max(power_values) if power_values else 0.0

    # Find the mean power across the full simulated day.
    average_power_w = (
        sum(power_values) / len(power_values)
        if power_values else 0.0
    )

    # Return both the detailed data and summary statistics.
    return {
        "time_series": results,
        "daily_energy_wh": daily_energy_wh,
        "daily_energy_kwh": daily_energy_kwh,
        "peak_power_w": peak_power_w,
        "average_power_w": average_power_w,
        "panel_area_m2": panel_area_m2,
        "panel_efficiency": panel_efficiency,
        "temperature_c": panel_temperature_c,
        "temperature_factor": temperature_factor,
        "shading_fraction": shading_fraction,
        "system_efficiency": system_efficiency,
    }


# ============================================================
# SECTION 8: EXPORTING RESULTS TO CSV
# ============================================================

def export_to_csv(simulation_results, filename="solar_results.csv"):
    """
    Save the solar time-series data to a CSV file.

    CSV files can be opened in Excel and analysed using Python.
    """

    # Extract the individual time-series records.
    records = simulation_results["time_series"]

    # Resolve the output path relative to the current working directory.
    output_path = Path(filename)

    # Create parent folders if they do not already exist.
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Open the file using UTF-8 encoding and newline-safe writing.
    with output_path.open("w", newline="", encoding="utf-8") as file:

        # Define the columns in the output file.
        fieldnames = [
            "time_hours",
            "irradiance_w_m2",
            "temperature_c",
            "temperature_factor",
            "power_w",
        ]

        # Create a CSV writer with a header row.
        writer = csv.DictWriter(file, fieldnames=fieldnames)
        writer.writeheader()

        # Write each time-series sample to the file.
        writer.writerows(records)

    # Return the path for display or further processing.
    return output_path


# ============================================================
# SECTION 9: PLOTTING SOLAR SIMULATION RESULTS
# ============================================================

def plot_solar_results(simulation_results, save_plot=False):
    """
    Plot irradiance, electrical power, and accumulated energy.

    Matplotlib is imported inside this function so that the
    mathematical model can still be imported without plotting.
    """

    try:
        import matplotlib.pyplot as plt
    except ImportError as error:
        raise ImportError(
            "Install Matplotlib using: pip install matplotlib"
        ) from error

    # Extract the recorded samples.
    records = simulation_results["time_series"]

    if not records:
        raise ValueError("No simulation data is available to plot.")

    # Separate the data into arrays for plotting.
    times = [row["time_hours"] for row in records]
    irradiance = [row["irradiance_w_m2"] for row in records]
    power = [row["power_w"] for row in records]

    # Calculate accumulated energy up to each recorded sample.
    accumulated_energy = [0.0]

    for index in range(1, len(records)):

        # Find the elapsed time since the preceding sample.
        delta_hours = times[index] - times[index - 1]

        # Use the average power over this interval.
        average_power = (power[index] + power[index - 1]) / 2.0

        # Convert power and elapsed hours into watt-hours.
        energy_increment = average_power * delta_hours

        # Add this interval's energy to the running total.
        accumulated_energy.append(
            accumulated_energy[-1] + energy_increment
        )

    # Create three separate graphs in one figure.
    figure, axes = plt.subplots(
        nrows=3,
        ncols=1,
        figsize=(11, 10),
        sharex=True,
    )

    # Graph 1: sunlight intensity throughout the day.
    axes[0].plot(times, irradiance, label="Solar irradiance")
    axes[0].set_ylabel("Irradiance (W/m²)")
    axes[0].set_title("Fluxxwave Solar Irradiance")
    axes[0].grid(True)
    axes[0].legend()

    # Graph 2: estimated electrical power from the panels.
    axes[1].plot(times, power, label="Solar electrical power")
    axes[1].set_ylabel("Power (W)")
    axes[1].set_title("Estimated Photovoltaic Power")
    axes[1].grid(True)
    axes[1].legend()

    # Graph 3: accumulated electrical energy.
    axes[2].plot(
        times,
        accumulated_energy,
        label="Accumulated solar energy",
    )
    axes[2].set_xlabel("Time of day (decimal hours)")
    axes[2].set_ylabel("Energy (Wh)")
    axes[2].set_title("Accumulated Solar Energy")
    axes[2].grid(True)
    axes[2].legend()

    # Add spacing so labels and titles do not overlap.
    figure.tight_layout()

    # Optionally save the figure to an image file.
    if save_plot:
        figure.savefig("solar_simulation.png", dpi=300)

    # Display the graphs.
    plt.show()


