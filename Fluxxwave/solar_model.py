def main():
    """
    Execute a demonstration of the solar model.

    Edit the parameters below to explore different scenarios.
    """

    # Configure the hypothetical Fluxxwave solar installation.
    simulation = simulate_solar_day(
        panel_area_m2=2.0,
        panel_efficiency=0.22,
        peak_irradiance=900.0,
        sunrise_hour=6.0,
        sunset_hour=18.0,
        step_minutes=10,
        shading_fraction=0.10,
        panel_temperature_c=35.0,
        system_efficiency=0.95,
        cloud_variability=0.15,
        random_seed=42,
    )

    # Print the summary of the simulated day.
    print_solar_summary(simulation)

    # Export the time-series records for later analysis.
    csv_path = export_to_csv(
        simulation,
        "data/solar_results.csv",
    )
    print(f"CSV results saved to: {csv_path}")

    # Generate and save the simulation graphs.
    plot_solar_results(simulation, save_plot=True)
    print("Graph saved to: solar_simulation.png")


# Run the demonstration only when this file is executed directly.
if __name__ == "__main__":
    main()
