# 3. ENERGY FLOW
# ============================================================

@dataclass
class EnergyFlow:
    """
    Energy transfers calculated during one simulation step.

    All energy fields use kWh.

    Sources:
        solar_generated_kwh:
            Energy generated by the solar panels during the interval.

        regenerative_recovered_kwh:
            Energy recovered from braking during the interval.

    Direct delivery:
        solar_to_load_kwh:
            Solar energy delivered directly to vehicle demand.

        regenerative_to_load_kwh:
            Recovered energy delivered directly to vehicle demand.

        battery_to_load_kwh:
            Electrical energy delivered from the battery side before
            accounting for the modeled discharge conversion loss.

    Battery charging:
        solar_to_battery_input_kwh and regen_to_battery_input_kwh
            Energy supplied to the charging process.

        battery_energy_stored_kwh:
            Energy actually added to battery storage.

    Losses:
        charging_loss_kwh and discharging_loss_kwh:
            Explicitly modeled conversion losses.

    These fields describe different stages of energy flow. Do not
    sum all fields as though each represents a separate energy source.
    """

    solar_generated_kwh: float = 0.0
    regenerative_recovered_kwh: float = 0.0

    solar_to_load_kwh: float = 0.0
    regenerative_to_load_kwh: float = 0.0
    battery_to_load_kwh: float = 0.0

    solar_to_battery_input_kwh: float = 0.0
    regen_to_battery_input_kwh: float = 0.0
    battery_energy_stored_kwh: float = 0.0

    charging_loss_kwh: float = 0.0
    discharging_loss_kwh: float = 0.0
    other_conversion_loss_kwh: float = 0.0

    vehicle_demand_kwh: float = 0.0
    unmet_vehicle_demand_kwh: float = 0.0
    curtailed_energy_kwh: float = 0.0

    def __post_init__(self) -> None:
        for name, value in self.to_dict().items():
            validate_finite_number(
                value,
                name,
                minimum=0.0,
            )

    @property
    def total_modeled_losses_kwh(self) -> float:
        """Sum the separately recorded conversion losses."""
        return (
            self.charging_loss_kwh
            + self.discharging_loss_kwh
            + self.other_conversion_loss_kwh
        )

    @property
    def total_direct_energy_to_load_kwh(self) -> float:
        """Sum direct solar, regenerative, and battery delivery."""
        return (
            self.solar_to_load_kwh
            + self.regenerative_to_load_kwh
            + self.battery_to_load_kwh
        )

    def to_dict(self) -> dict[str, Any]:
        """Return the energy-flow values as a dictionary."""
        return dataclass_to_dict(self)


