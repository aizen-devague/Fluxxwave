# 7. SIMULATION SUMMARY
# ============================================================

@dataclass
class SimulationSummary:
    """
    Aggregate results for an entire simulation run.
    """

    run_id: str
    duration_seconds: float
    recorded_steps: int

    solar_energy_kwh: float | None = None
    regenerative_energy_kwh: float | None = None
    vehicle_demand_kwh: float | None = None
    battery_energy_stored_kwh: float | None = None
    battery_energy_removed_kwh: float | None = None
    modeled_losses_kwh: float | None = None
    unmet_demand_kwh: float | None = None

    successful_switches: int = 0
    failed_switches: int = 0

    warnings: list[str] = field(default_factory=list)
    timestamp_utc: str = field(default_factory=utc_now_iso)

    def __post_init__(self) -> None:
        if not self.run_id.strip():
            raise ValueError("run_id cannot be empty.")

        validate_finite_number(
            self.duration_seconds,
            "duration_seconds",
            minimum=0.0,
        )

        if isinstance(self.recorded_steps, bool) or not isinstance(
            self.recorded_steps, int
        ):
            raise TypeError("recorded_steps must be an integer.")

        if self.recorded_steps < 0:
            raise ValueError("recorded_steps cannot be negative.")

        for name in (
            "solar_energy_kwh",
            "regenerative_energy_kwh",
            "vehicle_demand_kwh",
            "battery_energy_stored_kwh",
            "battery_energy_removed_kwh",
            "modeled_losses_kwh",
            "unmet_demand_kwh",
        ):
            value = getattr(self, name)
            if value is not None:
                validate_finite_number(
                    value,
                    name,
                    minimum=0.0,
                )

        if self.successful_switches < 0 or self.failed_switches < 0:
            raise ValueError("Switch counts cannot be negative.")

    def to_dict(self) -> dict[str, Any]:
        """Return the simulation summary as a dictionary."""
        return dataclass_to_dict(self)


