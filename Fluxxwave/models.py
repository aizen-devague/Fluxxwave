# 9. SCENARIO RESULT
# ============================================================

@dataclass
class ScenarioResult:
    """
    Performance metrics for one simulation scenario.

    Useful when comparing battery-selection strategies under
    equivalent driving profiles and environmental conditions.
    """

    scenario_name: str
    summary: SimulationSummary

    strategy_name: str = "default"
    description: str = ""

    solar_contribution_percent: float | None = None
    regenerative_contribution_percent: float | None = None
    modeled_loss_percent: float | None = None

    def __post_init__(self) -> None:
        if not self.scenario_name.strip():
            raise ValueError("scenario_name cannot be empty.")

        for name in (
            "solar_contribution_percent",
            "regenerative_contribution_percent",
            "modeled_loss_percent",
        ):
            value = getattr(self, name)
            if value is not None:
                validate_finite_number(value, name, minimum=0.0)

    def to_dict(self) -> dict[str, Any]:
        """Flatten scenario metadata and summary metrics."""
        result = {
            "scenario_name": self.scenario_name,
            "strategy_name": self.strategy_name,
            "description": self.description,
            "solar_contribution_percent":
                self.solar_contribution_percent,
            "regenerative_contribution_percent":
                self.regenerative_contribution_percent,
            "modeled_loss_percent": self.modeled_loss_percent,
        }

        for key, value in self.summary.to_dict().items():
            result[f"summary_{key}"] = value

        return result


