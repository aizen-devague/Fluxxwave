# 8. CONTROLLER EVENT
# ============================================================

@dataclass
class ControllerEvent:
    """
    A record of a supervisory-controller decision or warning.
    """

    event_type: str
    message: str
    severity: str = "INFO"
    component: str = "controller"

    step_index: int | None = None
    timestamp_utc: str = field(default_factory=utc_now_iso)
    details: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.event_type.strip():
            raise ValueError("event_type cannot be empty.")

        if not self.message.strip():
            raise ValueError("message cannot be empty.")

        allowed_severities = {
            "DEBUG",
            "INFO",
            "WARNING",
            "ERROR",
            "CRITICAL",
        }

        self.severity = self.severity.upper()

        if self.severity not in allowed_severities:
            raise ValueError(
                f"severity must be one of {sorted(allowed_severities)}."
            )

        if self.step_index is not None and self.step_index < 0:
            raise ValueError("step_index cannot be negative.")

    def to_dict(self) -> dict[str, Any]:
        """Return the controller event as a dictionary."""
        return dataclass_to_dict(self)


