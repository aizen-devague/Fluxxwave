# 4. BATTERY SNAPSHOT
# ============================================================

@dataclass
class BatterySnapshot:
    """
    A snapshot of one simulated battery at a particular time.

    This is a reporting structure. The Battery class remains
    responsible for its own simulation behaviour.
    """

    battery_id: str
    soc_percent: float
    capacity_kwh: float
    stored_energy_kwh: float
    available_energy_kwh: float

    enabled: bool = True
    available: bool = True
    temperature_c: float | None = None
    estimated_voltage_v: float | None = None
    faults: list[str] = field(default_factory=list)
    timestamp_utc: str = field(default_factory=utc_now_iso)

    def __post_init__(self) -> None:
        if not self.battery_id.strip():
            raise ValueError("battery_id cannot be empty.")

        for name in (
            "soc_percent",
            "capacity_kwh",
            "stored_energy_kwh",
            "available_energy_kwh",
        ):
            validate_finite_number(
                getattr(self, name),
                name,
                minimum=0.0,
            )

        if self.soc_percent > 100.0:
            raise ValueError("soc_percent cannot exceed 100.")

        if self.capacity_kwh <= 0:
            raise ValueError("capacity_kwh must be positive.")

        if self.stored_energy_kwh > self.capacity_kwh:
            raise ValueError(
                "stored_energy_kwh cannot exceed capacity_kwh."
            )

        if self.available_energy_kwh > self.stored_energy_kwh:
            raise ValueError(
                "available_energy_kwh cannot exceed stored energy."
            )

        if self.temperature_c is not None:
            validate_finite_number(
                self.temperature_c, "temperature_c"
            )

        if self.estimated_voltage_v is not None:
            validate_finite_number(
                self.estimated_voltage_v,
                "estimated_voltage_v",
                minimum=0.0,
            )

    def to_dict(self) -> dict[str, Any]:
        """Return a serializable snapshot."""
        return dataclass_to_dict(self)


