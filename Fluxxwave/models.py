
"""
Fluxxwave EV — Shared Data Models
==================================

Purpose:
    Define consistent data structures shared by Fluxxwave modules.

Models:
    1. OperatingConditions
    2. EnergyFlow
    3. BatterySnapshot
    4. SwitchingEvent
    5. SimulationStepResult
    6. SimulationSummary
    7. ControllerEvent
    8. ScenarioResult

Dependencies:
    Python standard library only.

Important:
    These models represent software simulation data. They are not
    battery-management hardware, safety controllers, or a substitute
    for a real battery management system (BMS).
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from typing import Any


# ============================================================
# 1. SHARED UTILITIES
# ============================================================

def utc_now_iso() -> str:
    """Return the current UTC timestamp in ISO 8601 format."""
    return datetime.now(timezone.utc).isoformat()


def validate_finite_number(
    value: float,
    field_name: str,
    *,
    minimum: float | None = None,
) -> None:
    """Validate that a numeric field contains a finite number."""
    import math

    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise TypeError(f"{field_name} must be numeric.")

    if not math.isfinite(value):
        raise ValueError(f"{field_name} must be finite.")

    if minimum is not None and value < minimum:
        raise ValueError(
            f"{field_name} must be at least {minimum}."
        )


def dataclass_to_dict(instance: Any) -> dict[str, Any]:
    """Convert a dataclass instance into a dictionary."""
    return asdict(instance)


