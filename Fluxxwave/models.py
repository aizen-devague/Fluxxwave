# 2. OPERATING CONDITIONS
# ============================================================

@dataclass
class OperatingConditions:
    """
    Inputs describing one simulation step.

    Units:
        speed_mps: metres per second
        irradiance_w_m2: watts per square metre
        ambient_temperature_c: degrees Celsius
        step_seconds: seconds

    braking indicates whether the simulation considers this interval
    a braking interval. Actual regenerative recovery still depends on
    the change in vehicle kinetic energy and model constraints.
    """

    speed_mps: float
    irradiance_w_m2: float
    braking: bool = False
    ambient_temperature_c: float = 25.0
    step_seconds: float = 60.0
    timestamp_utc: str = field(default_factory=utc_now_iso)

    def __post_init__(self) -> None:
        validate_finite_number(
            self.speed_mps, "speed_mps", minimum=0.0
        )
        validate_finite_number(
            self.irradiance_w_m2,
            "irradiance_w_m2",
            minimum=0.0,
        )
        validate_finite_number(
            self.ambient_temperature_c,
            "ambient_temperature_c",
        )
        validate_finite_number(
            self.step_seconds,
            "step_seconds",
            minimum=0.0,
        )

        if self.step_seconds == 0:
            raise ValueError("step_seconds must be greater than zero.")

        if not isinstance(self.braking, bool):
            raise TypeError("braking must be True or False.")


