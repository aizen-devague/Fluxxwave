# 6. SIMULATION STEP RESULT
# ============================================================

@dataclass
class SimulationStepResult:
    """
    Consolidated result of one simulation interval.

    This model groups operating conditions, energy transfers,
    battery snapshots, and numerical energy-balance diagnostics.
    """

    step_index: int
    conditions: OperatingConditions
    energy: EnergyFlow

    batteries: list[BatterySnapshot] = field(default_factory=list)
    active_battery_id: str | None = None

    energy_balance_error_kwh: float | None = None
    warnings: list[str] = field(default_factory=list)
    timestamp_utc: str = field(default_factory=utc_now_iso)

    def __post_init__(self) -> None:
        if isinstance(self.step_index, bool) or not isinstance(
            self.step_index, int
        ):
            raise TypeError("step_index must be an integer.")

        if self.step_index < 0:
            raise ValueError("step_index cannot be negative.")

        if self.energy_balance_error_kwh is not None:
            validate_finite_number(
                self.energy_balance_error_kwh,
                "energy_balance_error_kwh",
            )

    def to_dict(self) -> dict[str, Any]:
        """Return a nested dictionary of the simulation result."""
        return dataclass_to_dict(self)

    def to_flat_dict(self) -> dict[str, Any]:
        """
        Flatten the primary values for CSV export.

        Battery-specific fields are named battery_a_*, battery_b_*,
        etc. according to the battery_id supplied by the caller.
        """
        row: dict[str, Any] = {
            "step_index": self.step_index,
            "timestamp_utc": self.timestamp_utc,
            "speed_mps": self.conditions.speed_mps,
            "irradiance_w_m2": self.conditions.irradiance_w_m2,
            "braking": self.conditions.braking,
            "ambient_temperature_c":
                self.conditions.ambient_temperature_c,
            "step_seconds": self.conditions.step_seconds,
            "active_battery_id": self.active_battery_id,
            "energy_balance_error_kwh":
                self.energy_balance_error_kwh,
            **self.energy.to_dict(),
            "warnings": "; ".join(self.warnings),
        }

        for battery in self.batteries:
            prefix = battery.battery_id.lower().replace(" ", "_")

            row[f"{prefix}_soc_percent"] = battery.soc_percent
            row[f"{prefix}_stored_energy_kwh"] = (
                battery.stored_energy_kwh
            )
            row[f"{prefix}_available_energy_kwh"] = (
                battery.available_energy_kwh
            )
            row[f"{prefix}_temperature_c"] = battery.temperature_c
            row[f"{prefix}_estimated_voltage_v"] = (
                battery.estimated_voltage_v
            )
            row[f"{prefix}_enabled"] = battery.enabled
            row[f"{prefix}_available"] = battery.available
            row[f"{prefix}_faults"] = "; ".join(battery.faults)

        return row


