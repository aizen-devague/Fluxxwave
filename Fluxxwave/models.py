# 5. BATTERY SWITCHING EVENT
# ============================================================

@dataclass
class SwitchingEvent:
    """
    A record of a battery-selection or switching event.

    success=None means the outcome is unknown or was not recorded.
    """

    event_type: str
    from_battery: str | None
    to_battery: str | None

    success: bool | None = None
    reason: str = ""
    timestamp_utc: str = field(default_factory=utc_now_iso)
    details: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.event_type.strip():
            raise ValueError("event_type cannot be empty.")

        if self.success is not None and not isinstance(
            self.success, bool
        ):
            raise TypeError("success must be True, False, or None.")

    def to_dict(self) -> dict[str, Any]:
        """Return the switching event as a dictionary."""
        return dataclass_to_dict(self)


