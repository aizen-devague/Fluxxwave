# 10. BASIC SELF-TEST
# ============================================================

def run_demo() -> None:
    """Create and print an illustrative simulation-step result."""

    conditions = OperatingConditions(
        speed_mps=12.0,
        irradiance_w_m2=750.0,
        braking=False,
        ambient_temperature_c=25.0,
        step_seconds=60.0,
    )

    energy = EnergyFlow(
        solar_generated_kwh=0.004,
        solar_to_load_kwh=0.003,
        vehicle_demand_kwh=0.010,
        battery_to_load_kwh=0.007,
        discharging_loss_kwh=0.0004,
    )

    battery_a = BatterySnapshot(
        battery_id="Battery_A",
        soc_percent=75.0,
        capacity_kwh=2.0,
        stored_energy_kwh=1.5,
        available_energy_kwh=1.1,
        estimated_voltage_v=46.0,
    )

    result = SimulationStepResult(
        step_index=0,
        conditions=conditions,
        energy=energy,
        batteries=[battery_a],
        active_battery_id="Battery_A",
        energy_balance_error_kwh=None,
        warnings=[
            "Illustrative demonstration values; not measured data."
        ],
    )

    print("\nFLUXXWAVE MODELS — SELF-TEST")
    print("=" * 45)
    print("Simulation step:")
    for key, value in result.to_flat_dict().items():
        print(f"  {key}: {value}")

    print("\nModels created successfully.")


if __name__ == "__main__":
    run_demo()
