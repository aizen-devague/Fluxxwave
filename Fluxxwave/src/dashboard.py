# 8. OPTIONAL DEMONSTRATION
# ============================================================

def main():
    """
    Run a sample simulation and open the dashboard.

    The data is synthetic and intended only to demonstrate
    the plotting workflow.
    """

    try:
        from energy_simulator import (
            run_simulation,
            create_demo_profiles,
        )

    except ImportError as error:

        print(
            "Could not import energy_simulator.py.\n"
            "Make sure all Fluxxwave modules are in the "
            "same directory."
        )

        print("Import error:", error)

        return

    # Configure a one-hour demonstration.
    config = {
        "step_seconds": 60.0,
        "duration_seconds": 3600.0,
        "initial_speed_mps": 0.0,
    }

    number_of_steps = int(
        math.ceil(
            config["duration_seconds"]
            / config["step_seconds"]
        )
    )

    # Create the same type of example profiles used by the
    # main energy simulator.
    (
        drive_cycle,
        irradiance_profile,
        braking_profile,
    ) = create_demo_profiles(
        number_of_steps,
        config["step_seconds"],
    )

    # Run the energy simulation.
    simulation = run_simulation(
        config=config,
        drive_cycle=drive_cycle,
        irradiance_profile=irradiance_profile,
        braking_profile=braking_profile,
    )

    # Display and save the charts.
    show_dashboard(
        simulation_data=simulation,
        save_dir="data/dashboard",
        show=True,
    )


# ============================================================
