# 4. PLOT ACTIVE BATTERY AND SWITCHING HISTORY
# ============================================================

def plot_switching_history(
    simulation_data,
    controller=None,
    save_dir=None,
    show=True,
):
    """
    Display which battery was active over time and list
    recorded switching events.

    The active-battery plot uses the battery_history records.
    The event list uses the battery manager's switching_events.

    Controller events are also included when a controller
    state is provided.
    """

    require_matplotlib()

    simulation = extract_simulation_state(
        simulation_data
    )

    history = simulation.get("battery_history", [])

    if not history:
        print("No battery history is available.")
        return None

    times = get_time_axis(history)

    # Encode active battery identifiers as numeric values.
    # A = 1, B = 2, none/unknown = 0.
    active_values = []

    for record in history:

        active_id = record.get("active_battery_id")

        if active_id == "A":
            active_values.append(1)

        elif active_id == "B":
            active_values.append(2)

        else:
            active_values.append(0)

    fig, ax = plt.subplots(
        figsize=(12, 4),
    )

    ax.step(
        times,
        active_values,
        where="post",
        linewidth=2,
    )

    ax.set_yticks(
        [0, 1, 2],
        labels=["None", "Battery A", "Battery B"],
    )

    ax.set_ylim(-0.3, 2.3)

    ax.set_xlabel("Simulation time (hours)")

    ax.set_ylabel("Active battery")

    ax.set_title(
        "Fluxxwave — Active Battery History"
    )

    ax.grid(True, alpha=0.3)

    fig.tight_layout()

    save_figure(
        fig,
        save_dir,
        "switching_history.png",
    )

    # --------------------------------------------------------
    # Print the event log.
    # --------------------------------------------------------

    manager = simulation.get("battery_manager")

    switching_events = (
        manager.switching_events
        if manager is not None
        else []
    )

    print("\nBATTERY SWITCHING EVENTS")
    print("-" * 72)

    if switching_events:

        for event in switching_events:

            print(
                f"{event.get('timestamp', '')} | "
                f"{event.get('event_type', '')} | "
                f"{event.get('from_battery', '')} -> "
                f"{event.get('to_battery', '')} | "
                f"{event.get('reason', '')}"
            )

    else:

        print("No battery switching events were recorded.")

    # Controller events are a separate event stream.
    if controller is not None:

        controller_events = controller.get(
            "events",
            [],
        )

        print("\nSUPERVISORY CONTROLLER EVENTS")
        print("-" * 72)

        if controller_events:

            for event in controller_events:

                print(
                    f"{event.get('timestamp', '')} | "
                    f"{event.get('severity', '')} | "
                    f"{event.get('event_type', '')} | "
                    f"{event.get('message', '')}"
                )

        else:

            print("No controller events were recorded.")

    if show:
        plt.show()

    return fig


