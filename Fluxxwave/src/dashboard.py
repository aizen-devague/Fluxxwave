# 6. DISPLAY SIMULATION PROGRESS
# ============================================================

def display_progress(simulation_data):
    """
    Print the fraction of configured simulation duration
    that has elapsed.

    This reports the progress of a completed or partially
    completed simulation state. It is not a live progress bar.
    """

    simulation = extract_simulation_state(
        simulation_data
    )

    current_time = safe_float(
        simulation.get("time_seconds")
    )

    config = simulation.get("config", {})

    total_duration = safe_float(
        config.get("duration_seconds")
    )

    if total_duration <= 0:

        print("Simulation progress is unavailable.")

        return None

    progress_percent = min(
        100.0,
        max(
            0.0,
            current_time / total_duration * 100.0,
        ),
    )

    print(
        f"Simulation progress: {progress_percent:.1f}% "
        f"({current_time:.1f}s / {total_duration:.1f}s)"
    )

    return progress_percent


