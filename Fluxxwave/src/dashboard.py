# 3. PLOT POWER HISTORY
# ============================================================

def plot_power_history(
    simulation_data,
    save_dir=None,
    show=True,
):
    """
    Plot solar power, estimated regenerative power, and
    vehicle electrical demand.

    All plotted quantities are in watts.

    Important:
    Regenerative power is an estimate from the simplified
    simulation, not measured vehicle performance.
    """

    require_matplotlib()

    simulation = extract_simulation_state(
        simulation_data
    )

    history = simulation.get("power_history", [])

    if not history:
        print("No power history is available to plot.")
        return None

    times = get_time_axis(history)

    solar_power = [
        safe_float(record.get("solar_power_w"))
        for record in history
    ]

    regenerative_power = [
        safe_float(record.get("regenerative_power_w"))
        for record in history
    ]

    vehicle_demand = [
        safe_float(record.get("vehicle_demand_w"))
        for record in history
    ]

    traction_power = [
        safe_float(record.get("traction_power_w"))
        for record in history
    ]

    auxiliary_power = [
        safe_float(record.get("auxiliary_power_w"))
        for record in history
    ]

    # Two charts help distinguish the overall energy picture
    # from the individual demand components.
    fig, axes = plt.subplots(
        2,
        1,
        figsize=(12, 9),
        sharex=True,
    )

    fig.suptitle(
        "Fluxxwave — Power Monitoring",
        fontsize=16,
        fontweight="bold",
    )

    # --------------------------------------------------------
    # Chart 1: Solar, regeneration, and total demand.
    # --------------------------------------------------------

    axes[0].plot(
        times,
        solar_power,
        label="Solar electrical power",
        linewidth=2,
    )

    axes[0].plot(
        times,
        regenerative_power,
        label="Estimated regenerative power",
        linewidth=2,
    )

    axes[0].plot(
        times,
        vehicle_demand,
        label="Vehicle electrical demand",
        linewidth=2,
    )

    axes[0].set_ylabel("Power (W)")

    axes[0].set_title(
        "Generation and Vehicle Demand"
    )

    axes[0].grid(True, alpha=0.3)

    axes[0].legend()

    # --------------------------------------------------------
    # Chart 2: Vehicle demand components.
    # --------------------------------------------------------

    axes[1].plot(
        times,
        traction_power,
        label="Estimated traction power",
        linewidth=2,
    )

    axes[1].plot(
        times,
        auxiliary_power,
        label="Auxiliary power",
        linewidth=2,
    )

    axes[1].plot(
        times,
        vehicle_demand,
        label="Total electrical demand",
        linestyle="--",
        linewidth=2,
    )

    axes[1].set_xlabel("Simulation time (hours)")

    axes[1].set_ylabel("Power (W)")

    axes[1].set_title(
        "Electrical Demand Components"
    )

    axes[1].grid(True, alpha=0.3)

    axes[1].legend()

    fig.tight_layout(rect=(0, 0, 1, 0.96))

    save_figure(
        fig,
        save_dir,
        "power_history.png",
    )

    if show:
        plt.show()

    return fig


