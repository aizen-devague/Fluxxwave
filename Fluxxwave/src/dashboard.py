# 7. SHOW THE COMPLETE DASHBOARD
# ============================================================

def show_dashboard(
    simulation_data,
    controller=None,
    save_dir="data/dashboard",
    show=True,
):
    """
    Generate all static dashboard charts and text reports.

    Parameters
    ----------
    simulation_data:
        Raw simulation state or controller state.

    controller:
        Optional supervisory controller state. If simulation_data
        is already a controller state, this may be omitted.

    save_dir:
        Directory for PNG chart output. Use None to avoid saving.

    show:
        If True, display plots using Matplotlib.

    Returns
    -------
    dict
        Figure objects and key summary metrics.

    Example
    -------
    state = run_simulation(...)
    show_dashboard(state)

    Or:
    controller = initialize_controller(...)
    ...
    show_dashboard(controller, controller=controller)
    """

    require_matplotlib()

    # If the first argument is a controller, infer it.
    controller = extract_controller_state(
        simulation_data,
        controller,
    )

    simulation = extract_simulation_state(
        simulation_data
    )

    print("\n" + "=" * 68)
    print("FLUXXWAVE — SIMULATION DASHBOARD")
    print("=" * 68)

    display_progress(simulation)

    # Generate individual charts.
    battery_figure = plot_battery_history(
        simulation,
        save_dir=save_dir,
        show=False,
    )

    power_figure = plot_power_history(
        simulation,
        save_dir=save_dir,
        show=False,
    )

    switching_figure = plot_switching_history(
        simulation,
        controller=controller,
        save_dir=save_dir,
        show=False,
    )

    summary_figure = display_summary(
        simulation,
        controller=controller,
        save_dir=save_dir,
        show=False,
    )

    # Display the figures after generating them all.
    if show:

        plt.show()

    summary = get_summary(simulation)

    print("\nDashboard generation completed.")

    return {
        "battery_figure": battery_figure,
        "power_figure": power_figure,
        "switching_figure": switching_figure,
        "summary_figure": summary_figure,
        "summary": summary,
        "save_directory": (
            str(save_dir)
            if save_dir is not None
            else None
        ),
    }


