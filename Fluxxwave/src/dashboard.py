from pathlib import Path
from datetime import datetime

import math

# Matplotlib is used for static charts.
# Install it with:
# python -m pip install matplotlib
try:
    import matplotlib.pyplot as plt
    import matplotlib.dates as mdates

    MATPLOTLIB_AVAILABLE = True

except ImportError:
    plt = None
    mdates = None

    MATPLOTLIB_AVAILABLE = False


# ============================================================
# 1. GENERAL HELPERS
# ============================================================

def require_matplotlib():
    """Raise a helpful error if Matplotlib is not installed."""

    if not MATPLOTLIB_AVAILABLE:
        raise ImportError(
            "Matplotlib is required for dashboard plots.\n"
            "Install it with: python -m pip install matplotlib"
        )


def extract_simulation_state(data):
    """
    Accept either a raw simulation state or a controller state.

    Raw simulation state:
        {
            "energy_history": [...],
            "battery_history": [...],
            "power_history": [...],
            "summary": {...}
        }

    Controller state:
        {
            "simulation": <raw simulation state>,
            "events": [...],
            "warnings": [...],
            ...
        }

    Returns
    -------
    dict
        The underlying energy-simulation state.
    """

    if not isinstance(data, dict):
        raise TypeError(
            "Dashboard input must be a dictionary."
        )

    # Controller state contains the simulation under this key.
    if isinstance(data.get("simulation"), dict):
        return data["simulation"]

    # A raw simulation state already contains its own histories.
    if "energy_history" in data:
        return data

    raise ValueError(
        "Could not find simulation histories. Pass the "
        "dictionary returned by run_simulation(), or a "
        "controller dictionary containing 'simulation'."
    )


def extract_controller_state(data, controller=None):
    """
    Identify the controller state if one was supplied.

    The controller is optional because the dashboard can also
    display a simulation without a supervisory controller.
    """

    if controller is not None:
        return controller

    if (
        isinstance(data, dict)
        and "simulation" in data
        and "system_status" in data
    ):
        return data

    return None


def get_time_axis(history):
    """
    Convert time_seconds values into hours.

    The simulation stores elapsed seconds. Hours are easier
    to read on longer graphs.
    """

    return [
        record.get("time_seconds", 0.0) / 3600.0
        for record in history
    ]


def safe_float(value, default=0.0):
    """Convert a value to float without allowing invalid values."""

    try:
        number = float(value)

        if not math.isfinite(number):
            return default

        return number

    except (TypeError, ValueError):
        return default


def get_summary(simulation):
    """
    Return summary metrics, calculating them if necessary.
    """

    summary = simulation.get("summary")

    if isinstance(summary, dict):
        return summary

    # Import only when needed to avoid unnecessary dependencies.
    try:
        from energy_simulator import calculate_summary

        summary = calculate_summary(simulation)

        simulation["summary"] = summary

        return summary

    except (ImportError, KeyError, TypeError):
        return {}


def save_figure(fig, save_dir, filename):
    """
    Save a figure when an output directory is provided.

    If save_dir is None, the figure is not saved.
    """

    if save_dir is None:
        return None

    output_dir = Path(save_dir)

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    output_path = output_dir / filename

    fig.savefig(
        output_path,
        dpi=160,
        bbox_inches="tight",
    )

    print(f"Saved chart: {output_path}")

    return str(output_path)


