# 5. DISPLAY ENERGY SUMMARY
# ============================================================

def display_summary(
    simulation_data,
    controller=None,
    save_dir=None,
    show=True,
):
    """
    Display a text summary and a bar chart of energy metrics.

    The chart compares:
    - Solar generation.
    - Regenerative electrical energy.
    - Vehicle demand.
    - Energy removed from battery storage.
    - Energy stored in batteries.
    - Charging and discharging losses.
    - Curtailed energy.

    These values represent different categories of energy
    flow. They should not be added together indiscriminately:
    some are inputs, some are outputs, and some are internal
    transfers.
    """

    require_matplotlib()

    simulation = extract_simulation_state(
        simulation_data
    )

    summary = get_summary(simulation)

    if not summary:
        print("No summary metrics are available.")
        return None

    # --------------------------------------------------------
    # Print numerical summary.
    # --------------------------------------------------------

    print("\n" + "=" * 68)
    print("FLUXXWAVE — ENERGY SUMMARY")
    print("=" * 68)

    display_fields = [
        ("Simulation duration (s)", "simulation_duration_seconds"),
        ("Simulation steps", "simulation_steps"),
        ("Solar generated (kWh)", "solar_generated_kwh"),
        ("Regenerative energy (kWh)", "regenerative_electrical_kwh"),
        ("Vehicle demand (kWh)", "vehicle_demand_kwh"),
        ("Load supplied (kWh)", "load_supplied_kwh"),
        ("Unmet demand (kWh)", "unmet_vehicle_demand_kwh"),
        ("Load coverage (%)", "load_coverage_percent"),
        ("Energy removed from batteries (kWh)", "battery_energy_removed_kwh"),
        ("Energy stored in batteries (kWh)", "battery_energy_stored_kwh"),
        ("Charging losses (kWh)", "battery_charge_loss_kwh"),
        ("Discharging losses (kWh)", "battery_discharge_loss_kwh"),
        ("Curtailed solar (kWh)", "curtailed_solar_kwh"),
        ("Curtailed regenerative energy (kWh)", "curtailed_regenerative_kwh"),
        ("Final stored energy (kWh)", "final_battery_energy_kwh"),
        ("Maximum step balance error (kWh)", "maximum_absolute_step_balance_error_kwh"),
    ]

    for label, key in display_fields:

        value = summary.get(key)

        if value is None:
            formatted = "N/A"

        elif isinstance(value, (int, float)):
            formatted = f"{value:.6f}"

        else:
            formatted = str(value)

        print(f"{label:<45} {formatted:>18}")

    # --------------------------------------------------------
    # Draw an energy metric chart.
    # --------------------------------------------------------

    chart_labels = [
        "Solar generated",
        "Regenerative energy",
        "Vehicle demand",
        "Battery energy removed",
        "Battery energy stored",
        "Charging losses",
        "Discharging losses",
        "Curtailed solar",
        "Curtailed regeneration",
    ]

    chart_keys = [
        "solar_generated_kwh",
        "regenerative_electrical_kwh",
        "vehicle_demand_kwh",
        "battery_energy_removed_kwh",
        "battery_energy_stored_kwh",
        "battery_charge_loss_kwh",
        "battery_discharge_loss_kwh",
        "curtailed_solar_kwh",
        "curtailed_regenerative_kwh",
    ]

    chart_values = [
        safe_float(summary.get(key))
        for key in chart_keys
    ]

    fig, ax = plt.subplots(
        figsize=(13, 7),
    )

    positions = list(range(len(chart_labels)))

    ax.barh(
        positions,
        chart_values,
    )

    ax.set_yticks(
        positions,
        labels=chart_labels,
    )

    ax.invert_yaxis()

    ax.set_xlabel("Energy (kWh)")

    ax.set_title(
        "Fluxxwave — Energy Metrics",
        fontsize=14,
        fontweight="bold",
    )

    ax.grid(
        axis="x",
        alpha=0.3,
    )

    # Add numeric labels at the end of each bar.
    for position, value in zip(
        positions,
        chart_values,
    ):

        ax.text(
            value,
            position,
            f" {value:.4f}",
            va="center",
            fontsize=8,
        )

    fig.tight_layout()

    save_figure(
        fig,
        save_dir,
        "energy_summary.png",
    )

    # --------------------------------------------------------
    # Show supervisory warnings if a controller is supplied.
    # --------------------------------------------------------

    if controller is not None:

        print("\nSUPERVISORY STATUS")
        print("-" * 68)

        print(
            "System status:",
            controller.get("system_status", "UNKNOWN"),
        )

        print(
            "Status message:",
            controller.get("status_message", ""),
        )

        warnings = controller.get("warnings", [])

        print("\nWARNINGS")

        if warnings:

            for warning in warnings:
                print(f"- {warning}")

        else:

            print("No warnings currently recorded.")

        if controller.get("last_error"):
            print(
                "\nLast error:",
                controller["last_error"],
            )

    print("=" * 68)

    if show:
        plt.show()

    return fig


