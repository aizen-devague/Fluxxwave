# 2. PLOT BATTERY HISTORY
# ============================================================

def plot_battery_history(
    simulation_data,
    save_dir=None,
    show=True,
):
    """
    Plot Battery A and Battery B state over the simulation.

    Charts:
    1. State of charge (%).
    2. Stored energy (kWh).
    3. Available energy above each battery's minimum SoC.

    A vertical marker is not drawn for every switching event
    here; switching history is handled separately.

    Parameters
    ----------
    simulation_data:
        Raw simulation state or controller state.

    save_dir:
        Optional directory in which to save the graph.

    show:
        Whether to display the graph interactively.

    Returns
    -------
    matplotlib.figure.Figure
    """

    require_matplotlib()

    simulation = extract_simulation_state(
        simulation_data
    )

    history = simulation.get("battery_history", [])

    if not history:
        print("No battery history is available to plot.")
        return None

    times = get_time_axis(history)

    # Extract SoC data for each simulated battery.
    battery_a_soc = [
        safe_float(
            record.get("battery_a_soc_percent")
        )
        for record in history
    ]

    battery_b_soc = [
        safe_float(
            record.get("battery_b_soc_percent")
        )
        for record in history
    ]

    # Extract stored energy.
    battery_a_stored = [
        safe_float(
            record.get("battery_a_stored_kwh")
        )
        for record in history
    ]

    battery_b_stored = [
        safe_float(
            record.get("battery_b_stored_kwh")
        )
        for record in history
    ]

    # Extract energy available above the minimum SoC.
    battery_a_available = [
        safe_float(
            record.get("battery_a_available_kwh")
        )
        for record in history
    ]

    battery_b_available = [
        safe_float(
            record.get("battery_b_available_kwh")
        )
        for record in history
    ]

    # Three vertically arranged charts share the same time axis.
    fig, axes = plt.subplots(
        3,
        1,
        figsize=(12, 12),
        sharex=True,
    )

    fig.suptitle(
        "Fluxxwave — Battery Monitoring",
        fontsize=16,
        fontweight="bold",
    )

    # --------------------------------------------------------
    # Chart 1: State of charge.
    # --------------------------------------------------------

    axes[0].plot(
        times,
        battery_a_soc,
        label="Battery A SoC",
        linewidth=2,
    )

    axes[0].plot(
        times,
        battery_b_soc,
        label="Battery B SoC",
        linewidth=2,
    )

    # Reference line for the project's default switching point.
    axes[0].axhline(
        y=20.0,
        linestyle="--",
        label="20% reference threshold",
    )

    axes[0].set_ylabel("SoC (%)")

    axes[0].set_ylim(0, 100)

    axes[0].set_title("Battery State of Charge")

    axes[0].grid(True, alpha=0.3)

    axes[0].legend()

    # --------------------------------------------------------
    # Chart 2: Total stored energy.
    # --------------------------------------------------------

    axes[1].plot(
        times,
        battery_a_stored,
        label="Battery A stored energy",
        linewidth=2,
    )

    axes[1].plot(
        times,
        battery_b_stored,
        label="Battery B stored energy",
        linewidth=2,
    )

    axes[1].set_ylabel("Stored energy (kWh)")

    axes[1].set_title("Energy Stored in Each Battery")

    axes[1].grid(True, alpha=0.3)

    axes[1].legend()

    # --------------------------------------------------------
    # Chart 3: Usable energy above minimum SoC.
    # --------------------------------------------------------

    axes[2].plot(
        times,
        battery_a_available,
        label="Battery A available energy",
        linewidth=2,
    )

    axes[2].plot(
        times,
        battery_b_available,
        label="Battery B available energy",
        linewidth=2,
    )

    axes[2].set_xlabel("Simulation time (hours)")

    axes[2].set_ylabel("Available energy (kWh)")

    axes[2].set_title(
        "Available Energy Above Minimum SoC"
    )

    axes[2].grid(True, alpha=0.3)

    axes[2].legend()

    fig.tight_layout(rect=(0, 0, 1, 0.96))

    save_figure(
        fig,
        save_dir,
        "battery_history.png",
    )

    if show:
        plt.show()

    return fig


